"""Smooth overlapping alpha strokes with exact max-composite reconstruction.

Geometry is regularized before clipping to source ink, not by blurring the final
character. The alpha decomposition is inferred, not historical stroke annotation.
"""
from pathlib import Path
import argparse
import json
import subprocess

import cv2
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as ndi
from scipy.interpolate import PchipInterpolator
from skimage.registration import optical_flow_tvl1

from experiment import (ROOT, S, TEXT, PAPER, template, fit_template, extract_cells,
                        adapted, ink_image, font, reveal)

SIZE = 480


def registered_fields(gray, char):
    layers, phase = template(char)
    target = (255-gray)/255.
    layers, phase = fit_template(layers, phase, gray < 150)
    flow = optical_flow_tvl1(ndi.gaussian_filter(target,1.5),
                            ndi.gaussian_filter(layers.max(0),1.5),
                            attachment=12,tightness=.3,num_warp=8,num_iter=12)
    yy,xx=np.mgrid[:S,:S]
    coords=np.array([yy+flow[0],xx+flow[1]])
    warped=np.stack([ndi.map_coordinates(a,coords,order=1,mode='constant') for a in layers])
    progress=np.stack([ndi.map_coordinates(a,coords,order=1,mode='nearest') for a in phase])
    return warped,progress


def ribbon_envelope(support, phase, shape):
    """Fit a smooth centerline/width ribbon; return envelope and arc progress.

    Progress bins maintain the ordered path through turns. Width is measured
    normal to the local tangent, then smoothed independently from the centerline.
    The final source ink is NOT blurred or regenerated by this function.
    """
    mask=support>.2
    yy,xx=np.where(mask)
    if not len(xx):
        raise ValueError('Cannot infer a completely missing template stroke')
    p=phase[mask];points=[];positions=[]
    lo,hi=np.quantile(p,[.005,.995])
    edges=np.linspace(lo,hi+1e-6,25)
    for a,b in zip(edges[:-1],edges[1:]):
        chosen=(p>=a)&(p<b)
        if chosen.sum()<2:continue
        points.append([np.mean(xx[chosen]),np.mean(yy[chosen])])
        positions.append((a+b)/2)
    h,w=shape
    if len(points)<3:
        # Degenerate dot/near-constant phase: retain its isolated envelope.
        return (cv2.resize(mask.astype(np.uint8),(w,h),interpolation=cv2.INTER_NEAREST)>0,
                np.clip(cv2.resize(phase,(w,h),interpolation=cv2.INTER_CUBIC),0,1))
    points=ndi.gaussian_filter1d(np.array(points),.9,axis=0)
    tangent=np.gradient(points,axis=0)
    tangent/=np.maximum(np.linalg.norm(tangent,axis=1,keepdims=True),1e-5)
    normals=np.stack([-tangent[:,1],tangent[:,0]],axis=1)
    radii=[]
    for point,normal,t in zip(points,normals,positions):
        chosen=abs(p-t)<max((hi-lo)/20,.025)
        offsets=(np.stack([xx[chosen],yy[chosen]],axis=1)-point)@normal
        radii.append(max(1,float(np.quantile(abs(offsets),.90))))
    radii=ndi.gaussian_filter1d(np.array(radii),1.5)
    parameter=np.linspace(0,len(points)-1,160)
    path=PchipInterpolator(np.arange(len(points)),points)(parameter)
    radius=PchipInterpolator(np.arange(len(points)),radii)(parameter)
    tangent=np.gradient(path,axis=0)
    tangent/=np.maximum(np.linalg.norm(tangent,axis=1,keepdims=True),1e-5)
    normal=np.stack([-tangent[:,1],tangent[:,0]],axis=1)
    polygon=np.concatenate([path+normal*radius[:,None],(path-normal*radius[:,None])[::-1]])
    scale=np.array([w/support.shape[1],h/support.shape[0]])
    envelope=np.zeros((h,w),np.uint8)
    cv2.fillPoly(envelope,[np.round(polygon*scale).astype(np.int32)],1)
    for point,rad in [(path[0],radius[0]),(path[-1],radius[-1])]:
        cv2.ellipse(envelope,tuple(np.round(point*scale).astype(int)),
                    tuple(np.maximum(1,np.round(rad*scale)).astype(int)),0,0,360,1,-1)
    # Stable arc-length progress on the new centerline, extended over its width.
    path=path*scale
    lengths=np.r_[0,np.cumsum(np.linalg.norm(np.diff(path,axis=0),axis=1))]
    times=lengths/max(lengths[-1],1e-6)
    seeds=np.zeros((h,w),np.uint8);values=np.zeros((h,w),np.float32)
    for a,b,ta,tb in zip(path[:-1],path[1:],times[:-1],times[1:]):
        start=tuple(np.round(a).astype(int));end=tuple(np.round(b).astype(int))
        cv2.line(seeds,start,end,1,1)
        cv2.line(values,start,end,float((ta+tb)/2),1)
    if not seeds.any():raise ValueError('Ribbon centerline lies outside target')
    nearest=ndi.distance_transform_edt(seeds==0,return_distances=False,return_indices=True)
    progress=ndi.gaussian_filter(values[tuple(nearest)],.8)
    return envelope.astype(bool),np.clip(progress,0,1)


def smooth_decomposition(warped, progress, target, sigma=.7, feather=.65):
    """Return source-colored stroke layers and smooth per-layer progress.

    Smooth centerline/width ribbons replace jagged registration boundaries. Log-sigmoid
    affinities make overlapping soft masks. Dividing by the strongest affinity
    gives at least one full-strength layer at EVERY source pixel. Far-away
    affinities below 1/255 are zeroed; the winning layer is always preserved.
    Thus max(layers)==target, including unsupported source ink, at every pixel.
    This coverage constraint does not establish correct semantic ownership.
    """
    if warped.ndim!=3 or progress.shape!=warped.shape or target.ndim!=2:
        raise ValueError('Expected [stroke,y,x] fields and a 2D target')
    if sigma<0 or feather<=0 or not np.isfinite(warped).all() or not np.isfinite(progress).all():
        raise ValueError('Invalid fields or smoothing parameters')
    if not np.isfinite(target).all() or np.any((target<0)|(target>1)):
        raise ValueError('Target must contain finite ink intensities in [0,1]')
    h,w=target.shape
    scores=[];phases=[]
    for support,phase in zip(warped,progress):
        mask,ribbon_phase=ribbon_envelope(support,phase,target.shape)
        distance=ndi.distance_transform_edt(mask)-ndi.distance_transform_edt(~mask)
        distance=ndi.gaussian_filter(distance,sigma)
        scores.append(-np.logaddexp(0,-distance/feather))
        phases.append(ribbon_phase)
    scores=np.array(scores,dtype=np.float32)
    alpha=np.exp(scores-scores.max(0))
    alpha[alpha<1/255]=0
    layers=alpha*target[None]
    return layers.astype(np.float32),np.array(phases,dtype=np.float32),alpha


def smoothstep(x):
    x=np.clip(x,0,1)
    return x*x*(3-2*x)


def frame(sample, elapsed):
    """Max composite of per-stroke swept layers; no final-frame replacement."""
    n=len(sample['layers'])
    index=min(max(int(elapsed),0),n)
    out=sample['completed'][index].copy()
    if 0<=elapsed<n:
        phase=sample['phase'][index]
        sweep=smoothstep(((elapsed-index)-.86*phase)/.14)
        out=np.maximum(out,sample['layers'][index]*sweep)
    return out


def assemble(layers, phase, target):
    completed=np.concatenate([np.zeros_like(layers[:1]),np.maximum.accumulate(layers,axis=0)])
    return dict(layers=layers,phase=phase,target=target,completed=completed)


def validate(sample):
    error=float(np.max(np.abs(sample['layers'].max(0)-sample['target'])))
    if error>1e-6:
        raise AssertionError(f'Reconstruction error {error}')
    previous=frame(sample,0)
    assert not previous.any()
    n=len(sample['layers'])
    for t in np.linspace(0,n,n*8+1):
        current=frame(sample,t)
        assert np.all(current+1e-7>=previous)
        assert np.all(current<=sample['target']+1e-7)
        previous=current
    assert np.allclose(previous,sample['target'],atol=1e-6)
    contribution=np.diff(sample['completed'],axis=0).sum(axis=(1,2))
    return dict(max_reconstruction_error=error,
                retained_ink=float(previous.sum()/max(sample['target'].sum(),1)),
                no_new_ink_strokes=(np.where(contribution<.01)[0]+1).tolist(),
                new_ink_by_stroke=contribution.tolist())


def audit(name, samples, baselines):
    # Every isolated stroke is visible; opacity is retained, not binarized.
    cell=92
    im=Image.new('RGB',(15*cell+30,80+len(samples)*2*(cell+20)),PAPER)
    d=ImageDraw.Draw(im)
    d.text((20,15),f'{name}: isolated strokes / old hard masks above, smooth overlapping layers below',font=font(19),fill=(40,40,40))
    for j,(s,b) in enumerate(zip(samples,baselines)):
        for row in range(2):
            y=70+(2*j+row)*(cell+20)
            im.paste(ink_image(s['target'],cell),(15,y))
            layers=b['memberships']*b['original'][None] if row==0 else s['layers']
            for k,layer in enumerate(layers):
                x=15+(k+1)*cell
                im.paste(ink_image(layer,cell),(x,y))
                d.text((x+3,y+cell),str(k+1),font=font(11),fill=(75,75,70))
    im.save(ROOT/f'smooth-isolated-{name}.png')
    comparison=Image.new('RGB',(1200,70+len(samples)*240),PAPER)
    d=ImageDraw.Draw(comparison)
    for i,label in enumerate(['Target','Old reconstruction','Smooth reconstruction','Absolute error x 20']):
        d.text((i*300+12,15),label,font=font(18),fill=(40,40,40))
    for j,(s,b) in enumerate(zip(samples,baselines)):
        for col,ink in enumerate([s['target'],b['retained'],s['completed'][-1],np.abs(s['completed'][-1]-s['target'])*20]):
            comparison.paste(ink_image(ink,225),(col*300+30,65+j*240))
    comparison.save(ROOT/f'smooth-reconstruction-{name}.png')


def detail(samples, baselines):
    im=Image.new('RGB',(1440,1110),PAPER);d=ImageDraw.Draw(im)
    for row,(j,k) in enumerate([(1,0),(5,5),(8,0),(8,2)]):
        b=baselines['reference'][j];s=samples['reference'][j]
        for col,ink in enumerate([s['target'],b['memberships'][k]*b['original'],s['layers'][k]]):
            im.paste(ink_image(ink,240),(90+col*480,70+row*250))
    for col,label in enumerate(['Target','Previous isolated stroke','New ribbon stroke']):
        d.text((30+col*480,20),label,font=font(23),fill=(40,40,40))
    d.text((30,1080),'Generated artwork. Smooth inferred envelopes; natural ink texture is retained.',font=font(18),fill=(100,100,90))
    im.save(ROOT/'Smooth-Stroke-Detail.png')


def video(samples, baselines):
    fps,step,gap,lead,hold=30,.38,.25,.6,3
    timeline=[];cursor=0
    for name in ['reference','light']:
        for j,s in enumerate(samples[name]):
            duration=lead+len(s['layers'])*step+gap
            timeline.append((cursor,name,j));cursor+=duration
        cursor+=hold
    width,height=1440,900
    out=ROOT/'Lishu-Smooth-Strokes.mp4'
    proc=subprocess.Popen(['ffmpeg','-y','-v','error','-f','rawvideo','-pixel_format','rgb24',
        '-video_size',f'{width}x{height}','-framerate',str(fps),'-i','pipe:0','-an','-c:v','libx264',
        '-preset','fast','-crf','18','-pix_fmt','yuv420p','-movflags','+faststart',str(out)],stdin=subprocess.PIPE)
    try:
        for f in range(int(np.ceil(cursor*fps))):
            t=f/fps
            start,name,j=max((s for s in timeline if s[0]<=t),key=lambda s:s[0])
            s=samples[name][j];b=baselines[name][j];n=len(s['layers'])
            elapsed=max(0,(t-start-lead)/step)
            active=min(int(elapsed),n-1)
            im=Image.new('RGB',(width,height),PAPER);d=ImageDraw.Draw(im)
            d.text((35,22),'LISHU / SMOOTH STROKES, COMPLETE RECONSTRUCTION',font=font(29),fill=(40,40,40))
            d.text((35,70),f'{name.upper()} SHEET   /   character {j+1}/10   /   stroke {active+1}/{n}',font=font(20),fill=(120,95,60))
            for col,label in enumerate(['PREVIOUS HARD MASKS','SMOOTH OVERLAPPING LAYERS','CURRENT ISOLATED STROKE']):
                x=35+480*col
                d.text((x,125),label,font=font(18),fill=(55,55,50))
                ink=[reveal(b,elapsed),frame(s,elapsed),s['layers'][active]][col]
                im.paste(ink_image(ink,365),(x+30,165))
                if col<2:
                    for k in range(10):
                        row,pos=divmod(k,5)
                        if col==0:
                            a=baselines[name][k]
                            glyph=a['retained'] if k<j else reveal(a,elapsed) if k==j else np.zeros((S,S))
                        else:
                            a=samples[name][k]
                            glyph=a['target'] if k<j else frame(a,elapsed) if k==j else np.zeros((SIZE,SIZE))
                        im.paste(ink_image(glyph,78),(x+pos*87,620+row*95))
                else:
                    im.paste(ink_image(s['target'],150),(x+132,620))
                    d.text((x+124,780),'Target character',font=font(17),fill=(90,90,80))
            d.text((35,550),f"Final retained ink: {100*(1-b['dropped']):.2f}%",font=font(18),fill=(90,90,80))
            d.text((515,550),'Final reconstruction: 100% of normalized target ink',font=font(17),fill=(90,90,80))
            d.text((35,835),'Smooth stroke envelopes + source ink + shared intersections. No whole-character fill at the end.',font=font(19),fill=(70,70,60))
            d.text((35,870),'Automatic decomposition; stroke ownership and historical writing order remain inferred.',font=font(16),fill=(110,110,100))
            proc.stdin.write(im.tobytes())
            if f%900==0:print('video',round(t,1),'/',round(cursor,1),flush=True)
        proc.stdin.close()
        if proc.wait()!=0:raise RuntimeError('FFmpeg failed')
    except BaseException:
        proc.kill();proc.wait();raise
    return dict(duration_seconds=cursor,fps=fps,resolution=[width,height],stroke_seconds=step)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--video',action='store_true')
    args=parser.parse_args()
    work=ROOT/'work'/'smooth';work.mkdir(parents=True,exist_ok=True)
    samples={};baselines={};report={'analysis_resolution':S,'layer_resolution':SIZE,'samples':[]}
    for name,path in [('reference','target-lishu.png'),('light','target-lishu-light.png')]:
        small=extract_cells(ROOT/path);large=extract_cells(ROOT/path,size=SIZE)
        samples[name]=[];baselines[name]=[]
        for j,(char,gray,big) in enumerate(zip(TEXT,small,large)):
            warped,phase=registered_fields(gray,char)
            target=((255-big)/255).astype(np.float32)
            layers,progress,alpha=smooth_decomposition(warped,phase,target)
            s=assemble(layers,progress,target);b=adapted(gray,char)
            record={'sheet':name,'char':char,'index':j,**validate(s)}
            # Count ink with no original geometric support, showing the amount
            # of extrapolation required by the exact reconstruction constraint.
            raw=cv2.resize(warped.max(0),(SIZE,SIZE),interpolation=cv2.INTER_LINEAR)>.2
            record['ink_outside_raw_template_support']=float(target[~raw].sum()/max(target.sum(),1))
            report['samples'].append(record)
            samples[name].append(s);baselines[name].append(b)
            np.savez_compressed(work/f'{name}-{j:02}.npz',layers=layers,phase=progress,target=target)
            print(name,char,'max error',record['max_reconstruction_error'],'no new ink',record['no_new_ink_strokes'],flush=True)
        audit(name,samples[name],baselines[name])
    detail(samples,baselines)
    (ROOT/'smooth-metrics.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    if args.video:
        report['video']=video(samples,baselines)
        (ROOT/'smooth-metrics.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')


if __name__=='__main__':
    main()
